#!/usr/bin/env bash
# Regenerate the topic index (README.md) on main from every other branch's README.md.
set -euo pipefail

REPO="${REPO:-mccannical/research-explain-understand}"

# Collect branch names (local + remote), excluding main and HEAD.
branches=$(
  {
    git for-each-ref --format='%(refname:short)' refs/heads/ 2>/dev/null
    git for-each-ref --format='%(refname:short)' refs/remotes/origin/ 2>/dev/null
  } | sed 's#^origin/##' | grep -v -E '^(main|master|HEAD)$' | sort -u
)

{
  echo "# Topic Index"
  echo ""
  echo "A collection of topics I'm learning, exploring, and explaining."
  echo "Each topic lives on its own branch; click through to read it."
  echo ""
  echo "| Topic | Preview |"
  echo "|---|---|"

  for b in $branches; do
    [ -z "$b" ] && continue
    [ "$b" = "HEAD" ] && continue

    readme="$(git show "origin/$b:README.md" 2>/dev/null || git show "$b:README.md" 2>/dev/null || true)"
    if [ -z "$readme" ]; then
      # fall back to any markdown file at root
      readme="$(git show "origin/$b:README.md" 2>/dev/null || true)"
    fi

    title="$(printf '%s\n' "$readme" | grep -m1 -E '^#{1,6} ' | sed -E 's/^#{1,6} *//')"
    [ -z "$title" ] && title="$b"

    # First non-heading, non-empty line as a short preview.
    preview="$(printf '%s\n' "$readme" | grep -v -E '^#{1,6} ' | grep -v -E '^[[:space:]]*$' | head -n1 | cut -c1-120)"
    [ -z "$preview" ] && preview="_(no description)_"

    url="https://github.com/${REPO}/blob/${b}/README.md"
    echo "| [${title}](${url}) | ${preview} |"
  done

  echo ""
  echo "_Generated by \`scripts/generate_index.sh\`._"
  echo ""
} > README.md

echo "Wrote README.md"
